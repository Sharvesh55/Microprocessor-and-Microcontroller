; EXPERIMENT 4
; String and Block Data Operations
; 8086 Microprocessor

ORG 100H

; Initialize source string
MOV BYTE PTR [3000H], 'H'
MOV BYTE PTR [3001H], 'E'
MOV BYTE PTR [3002H], 'L'
MOV BYTE PTR [3003H], 'L'
MOV BYTE PTR [3004H], 'O'

; Initialize destination
MOV DI, 4000H
MOV SI, 3000H
MOV CX, 05

; String Copy
CLD
REP MOVSB

; String Comparison
MOV SI, 3000H
MOV DI, 4000H
MOV CX, 05

CLD
REPE CMPSB

JZ EQUAL

MOV BYTE PTR [2000H], 00H
JMP FINISH

EQUAL:
MOV BYTE PTR [2000H], 01H

FINISH:
HLT
