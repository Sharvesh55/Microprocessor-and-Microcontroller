; EXPERIMENT 7
; Arithmetic Coprocessor Operations
; 8086 / 8087 Microprocessor

.MODEL SMALL
.8087

.DATA

NUM1 DD 5.5
NUM2 DD 2.5

ADD_RESULT DD ?
SUB_RESULT DD ?
MUL_RESULT DD ?
DIV_RESULT DD ?

.CODE

MAIN PROC

MOV AX, @DATA
MOV DS, AX

FINIT

; Floating Point Addition
FLD NUM1
FADD NUM2
FSTP ADD_RESULT

; Floating Point Subtraction
FLD NUM1
FSUB NUM2
FSTP SUB_RESULT

; Floating Point Multiplication
FLD NUM1
FMUL NUM2
FSTP MUL_RESULT

; Floating Point Division
FLD NUM1
FDIV NUM2
FSTP DIV_RESULT

; Exit
MOV AH, 4CH
INT 21H

MAIN ENDP
END MAIN
