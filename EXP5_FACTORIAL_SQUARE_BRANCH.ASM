; EXPERIMENT 5
; Factorial, Square, Branch and Subroutine
; 8086 Microprocessor

ORG 100H

; Factorial of 5
MOV AX, 0001H
MOV CX, 05

FACTORIAL:
MUL CX
LOOP FACTORIAL

MOV [2000H], AX

; Square of 5
MOV AL, 05H
MUL AL
MOV [2002H], AX

; Largest of Two Numbers
MOV AL, 25H
MOV BL, 15H

CMP AL, BL
JAE FIRST

MOV [2004H], BL
JMP SUBROUTINE

FIRST:
MOV [2004H], AL

; Subroutine Addition
SUBROUTINE:
MOV AX, 0005H
MOV BX, 0003H

CALL ADDITION

MOV [2005H], AX

HLT

ADDITION:
ADD AX, BX
RET
